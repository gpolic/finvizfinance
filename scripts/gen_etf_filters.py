#!/usr/bin/env python3
"""Regenerate ``finvizfinance/etf_constants.py`` from the live ETF screener.

The library reads ETF filters from the live page at runtime; this file is
only the fallback snapshot used when that fails. Elite-only filters and
options are left out: a free account cannot use them.

Usage::

    python scripts/gen_etf_filters.py            # fetch from finviz
    python scripts/gen_etf_filters.py page.html  # read a saved page
"""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from finvizfinance import util  # noqa: E402
from finvizfinance.screener.etf_filters import (  # noqa: E402
    ETF_SCREENER_URL,
    parse_etf_filters,
)

OUT = os.path.join(os.path.dirname(__file__), "..", "finvizfinance", "etf_constants.py")

HEADER = '''"""
ETF screener filters (finviz ``/screener/etf``).

Generated by ``scripts/gen_etf_filters.py`` from the filter definitions
embedded in the finviz ETF screener page. Elite-only filters and options are
left out. Do not edit by hand.
"""

from __future__ import annotations

ETF_FILTERS: dict[str, dict] = {
'''


def render(filters: dict[str, dict]) -> str:
    lines = [HEADER.rstrip("\n")]
    for title, f in filters.items():
        lines.append(f"    {json.dumps(title)}: {{")
        lines.append(f'        "prefix": {json.dumps(f["prefix"])},')
        lines.append('        "option": {')
        for label, value in f["option"].items():
            label = json.dumps(label, ensure_ascii=False)
            lines.append(f"            {label}: {json.dumps(value)},")
        lines.append("        },")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf8") as fh:
            html = fh.read()
    else:
        html = str(util.web_scrap(ETF_SCREENER_URL))
    try:
        filters = parse_etf_filters(html)
    except ValueError as err:
        raise SystemExit(str(err)) from err
    with open(OUT, "w", encoding="utf8", newline="\n") as fh:
        fh.write(render(filters))
    print(f"Wrote {len(filters)} filters: {list(filters)}")


if __name__ == "__main__":
    main()
